def get_house_lord_positions(chart):
    houses = chart["houses"]
    planets = chart["planets"]

    result = []

    for house_num, house_data in houses.items():
        lord = house_data["lord"]

        if lord in planets:
            lord_house = planets[lord]["house"]
            lord_sign = planets[lord]["sign"]
            lord_position = planets[lord]["full_text"]

            result.append({
                "house": house_num,
                "house_sign": house_data["sign"],
                "lord": lord,
                "lord_house": lord_house,
                "lord_sign": lord_sign,
                "lord_position": lord_position,
                "interpretation": interpret_house_lord(house_num, lord_house)
            })

    return result


